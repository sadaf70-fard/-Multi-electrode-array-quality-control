# fit the Random Forest on all labelled wells (same config as evaluated)
rf = RandomForestClassifier(n_estimators=500, class_weight="balanced_subsample", random_state=42)
rf.fit(X, y)

# exact, fast explainer for tree models
explainer = shap.TreeExplainer(rf)
sv = explainer.shap_values(X)

# pick the "fail" class (SHAP's output shape varies by version)
if isinstance(sv, list):        vals = sv[1]            # list: one array per class
elif sv.ndim == 3:              vals = sv[:, :, 1]      # (samples, features, classes)
else:                           vals = sv

shap.summary_plot(vals, X, feature_names=feats, plot_type="violin", show=True)

import matplotlib.pyplot as plt

shap.summary_plot(vals, X, feature_names=feats, plot_type="violin", show=False)
plt.tight_layout()
plt.savefig("shap_rf_violin.png", dpi=300, bbox_inches="tight")   # or .pdf for vector quality
