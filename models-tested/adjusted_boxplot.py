import numpy as np
import pandas as pd
from statsmodels.stats.stattools import medcouple

MIN_WELLS = 10

def adjusted_fence(x):
    """Adjusted-boxplot lower and upper limits."""
    x = pd.Series(x).dropna().to_numpy(float)
    q1, q3 = np.percentile(x, [25, 75])
    iqr = q3 - q1
    mc = float(medcouple(x))
    a, b = (-4, 3) if mc >= 0 else (-3, 4)

    lo = q1 - 1.5 * np.exp(a * mc) * iqr
    hi = q3 + 1.5 * np.exp(b * mc) * iqr

    return lo, hi, mc


wide = pd.read_csv("low_activity_wells_flagged (2).csv")
#good = wide["QC_low_activity"] == "pass"

ids = [
    "Barcode", "Plate", "Timepoint_dpp", "Well", "Control",
    "QC_low_activity", "Adjusted_boxplot_outlier",
    "outlier_features", "n_features_flagged"
]

features = [
    c for c in wide.select_dtypes(include=np.number).columns
    if c not in ids
]

outlier = pd.Series(False, index=wide.index)

low_hits = pd.DataFrame(False, index=wide.index, columns=features)
high_hits = pd.DataFrame(False, index=wide.index, columns=features)

# Store feature limits
bands = []

for (plate, dpp), grp in wide.groupby(["Plate", "Timepoint_dpp"]):

    here = (
        (wide["Plate"] == plate) &
        (wide["Timepoint_dpp"] == dpp)
    )

    for f in features:
        v = grp[f].dropna()

        if len(v) < MIN_WELLS:
            continue

        lo, hi, mc = adjusted_fence(v)

        bands.append({
            "Plate": plate,
            "Timepoint_dpp": dpp,
            "Feature": f,
            "Lower_band": lo,
            "Upper_band": hi,
            "Medcouple": mc,
            "Number_of_wells": len(v)
        })

        current_low = here & (wide[f] < lo)
        current_high = here & (wide[f] > hi)

        low_hits.loc[current_low, f] = True
        high_hits.loc[current_high, f] = True

        outlier |= current_low | current_high


wide["Adjusted_boxplot_outlier"] = "dead_well"
wide.loc[outlier, "Adjusted_boxplot_outlier"] = "yes"
wide.loc[~outlier, "Adjusted_boxplot_outlier"] = "no"

wide["outlier_features"] = [
    "; ".join(
        [f"{f} (low)" for f in features if low_hits.at[i, f]] +
        [f"{f} (high)" for f in features if high_hits.at[i, f]]
    )
    for i in wide.index
]

wide["n_features_flagged"] = (
    low_hits.sum(axis=1) + high_hits.sum(axis=1)
).astype(int)


# Save outlier results
wide.to_csv("adjusted_boxplot_outliers.csv", index=False)


# Create and save lower/upper-band table
bands_df = pd.DataFrame(bands)

bands_df[["Lower_band", "Upper_band", "Medcouple"]] = (
    bands_df[["Lower_band", "Upper_band", "Medcouple"]].round(3)
)

bands_df.to_csv(
    "adjusted_boxplot_feature_bands.csv",
    index=False
)


