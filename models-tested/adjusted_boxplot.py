import numpy as np
import pandas as pd
from statsmodels.stats.stattools import medcouple

MIN_WELLS = 10
K_VALUES = [1.0, 1.5, 2.0, 2.5, 3.0]


def adjusted_fence(x, k=1.5):
    x = pd.Series(x).dropna().to_numpy(float)
    q1, q3 = np.percentile(x, [25, 75])
    iqr = q3 - q1
    mc = float(medcouple(x))
    a, b = (-4, 3) if mc >= 0 else (-3, 4)

    return (
        q1 - k * np.exp(a * mc) * iqr,
        q3 + k * np.exp(b * mc) * iqr,
        mc
    )


wide = pd.read_csv("low_activity_wells_flagged (2).csv")
#good = wide["QC_low_activity"].eq("pass")

exclude = [
    "Barcode", "Plate", "Timepoint_dpp", "Well", "Control",
    "QC_low_activity", "Adjusted_boxplot_outlier",
    "outlier_features", "n_features_flagged"
]

features = [
    c for c in wide.select_dtypes(include=np.number)
    if c not in exclude
]

comparison = []
all_results = []

for k in K_VALUES:

    outlier = pd.Series(False, index=wide.index)
    feature_count = 0

    for (plate, dpp), grp in wide.groupby(
        ["Plate", "Timepoint_dpp"]
    ):
        here = (
            wide["Plate"].eq(plate) &
            wide["Timepoint_dpp"].eq(dpp)
        )

        for feature in features:

            values = grp[feature].dropna()

            if len(values) < MIN_WELLS:
                continue

            lo, hi, mc = adjusted_fence(values, k)

            low = here & wide[feature].lt(lo)
            high = here & wide[feature].gt(hi)
            flagged = low | high

            outlier |= flagged
            feature_count += flagged.sum()

            for i in wide.index[flagged]:
                all_results.append({
                    "K": k,
                    "Plate": plate,
                    "Timepoint_dpp": dpp,
                    "Well": wide.loc[i, "Well"],
                    "Feature": feature,
                    "Value": wide.loc[i, feature],
                    "Direction": "low" if low.loc[i] else "high",
                    "Lower_band": lo,
                    "Upper_band": hi,
                    "Medcouple": mc
                })

    column = f"Adjusted_K_{str(k).replace('.', '_')}"

    wide[column] = "dead_well"
    wide.loc[~outlier, column] = "pass"
    wide.loc[outlier, column] = "fail"

    comparison.append({
        "K": k,
        "Outlier_wells": int(outlier.sum()),
        "Feature_outliers": int(feature_count)
    })


comparison_df = pd.DataFrame(comparison)
results_df = pd.DataFrame(all_results)

wide.to_csv(
    "adjusted_boxplot_K_sensitivity.csv",
    index=False
)

comparison_df.to_csv(
    "adjusted_boxplot_K_comparison.csv",
    index=False
)

results_df.to_csv(
    "adjusted_boxplot_all_K_outliers.csv",
    index=False
)

