# =============================================================================
# NEURAL-NETWORK TUNING - one-at-a-time exploration around the base config.
# 13 configurations (base + 12 variants), each evaluated with REPEATS=3
# repeats of the shuffled group-aware CV (screening budget). Results are
# written to CSV after EVERY config, so nothing is lost mid-run.
# The winner should then be re-run with the full 10-repeat cell for the
# headline numbers. Expects X, y, g from the data cell above.
# =============================================================================
import numpy as np, pandas as pd
from scipy.stats import t
from sklearn.preprocessing import PowerTransformer, StandardScaler
from sklearn.model_selection import StratifiedGroupKFold
from sklearn.metrics import (roc_auc_score, average_precision_score, precision_score,
                             recall_score, f1_score, matthews_corrcoef, log_loss)
from tensorflow import keras

REPEATS = 10                                   # screening repeats per config (winner gets 10 later)

# --- the grid: base config + one-at-a-time variants (matches Table tab:nnconfig) ---
BASE = dict(layers=(32, 16), dropout=0.2, l2=1e-3, lr=1e-3, batch=16)
GRID = {"layers": [(16, 8), (64, 32)],
        "dropout": [0.0, 0.4],
        "l2":      [1e-4, 1e-2],
        "lr":      [1e-4, 1e-2],
        "batch":   [8, 32]}

CONFIGS = [("base", dict(BASE))]
for knob, vals in GRID.items():
    for v in vals:
        cfg = dict(BASE); cfg[knob] = v
        CONFIGS.append((f"{knob}={v}", cfg))                 # e.g. "dropout=0.4"
CONFIGS = [n for n in CONFIGS if n[0] == "layers=(16, 8)"]
# --- parameterised network (same shape as the base build(), knobs exposed) ---
def build(nf, seed, layers, dropout, l2, lr):
    ki = keras.initializers.HeNormal(seed=seed); reg = keras.regularizers.l2(l2)
    L = [keras.layers.Input((nf,))]
    for units in layers:
        L += [keras.layers.Dense(units, "relu", kernel_initializer=ki, kernel_regularizer=reg),
              keras.layers.Dropout(dropout)]
    L += [keras.layers.Dense(1, "sigmoid", kernel_initializer=ki)]
    m = keras.Sequential(L)
    m.compile(keras.optimizers.Adam(lr), "binary_crossentropy")
    return m

def mean_ci(v):                                # mean and 95% CI half-width (t-based)
    v = np.asarray(v, float)
    h = t.ppf(.975, len(v)-1) * v.std(ddof=1) / np.sqrt(len(v)) if len(v) > 1 else 0.0
    return v.mean(), h

# --- one config = repeated shuffled group-aware CV, identical to the main harness ---
def evaluate_config(cfg):
    per_repeat = []
    for seed in range(REPEATS):
        keras.utils.set_random_seed(seed)
        cv = StratifiedGroupKFold(3, shuffle=True, random_state=seed)
        oof = np.zeros(len(y))
        for tr, te in cv.split(X, y, g):                                   # test on unseen recordings
            pt = PowerTransformer("yeo-johnson").fit(X[tr])                # fitted on train fold only
            sc = StandardScaler().fit(pt.transform(X[tr]))
            Xtr = sc.transform(pt.transform(X[tr])); Xte = sc.transform(pt.transform(X[te]))
            cw = {0: 1., 1: (y[tr] == 0).sum() / max((y[tr] == 1).sum(), 1)}
            perm = np.random.RandomState(seed).permutation(len(Xtr))       # representative val split
            es = keras.callbacks.EarlyStopping(monitor="val_loss", patience=20,
                                               restore_best_weights=True)
            m = build(X.shape[1], seed, cfg["layers"], cfg["dropout"], cfg["l2"], cfg["lr"])
            m.fit(Xtr[perm], y[tr][perm], validation_split=0.2, epochs=200,
                  batch_size=cfg["batch"], class_weight=cw, verbose=0, callbacks=[es])
            oof[te] = m.predict(Xte, verbose=0).ravel()
        p = (oof >= 0.5).astype(int)
        per_repeat.append(dict(ROC_AUC=roc_auc_score(y, oof), PR_AUC=average_precision_score(y, oof),
                               Precision=precision_score(y, p, zero_division=0),
                               Recall=recall_score(y, p, zero_division=0),
                               F1=f1_score(y, p, zero_division=0),
                               MCC=matthews_corrcoef(y, p), LogLoss=log_loss(y, oof)))
    return per_repeat

# --- run all configs; SAVE AFTER EVERY ONE so nothing is ever lost -----------
summary, detail = [], []
for name, cfg in CONFIGS:
    print(f"running: {name}", flush=True)
    per = evaluate_config(cfg)
    for i, r in enumerate(per):
        detail.append(dict(config=name, repeat=i, **r))
    row = dict(config=name, **{k: (str(v) if k == "layers" else v) for k, v in cfg.items()})
    for mname in per[0]:
        mu, h = mean_ci([r[mname] for r in per])
        row[mname] = f"{mu:.3f} +/- {h:.3f}"               # formatted for the report
        row[mname + "_mean"] = round(mu, 4)                 # numeric for sorting
    summary.append(row)
    pd.DataFrame(summary).to_csv("nn_tuning_results.csv", index=False)     # incremental save
    pd.DataFrame(detail).to_csv("nn_tuning_per_repeat.csv", index=False)   # full per-repeat record

# --- final ranked summary ----------------------------------------------------
res = pd.DataFrame(summary).sort_values("MCC_mean", ascending=False)
print("\nRanked by MCC (mean over", REPEATS, "repeats):\n")
print(res[["config", "MCC", "PR_AUC", "ROC_AUC", "F1", "LogLoss"]].to_string(index=False))
